// Текущий язык (выбор хранится в браузере):
let LANG = (() => { try { return JSON.parse(localStorage.getItem('sysdeck.lang')) || 'en'; } catch { return 'en'; } })();
if (LANG !== 'ru' && LANG !== 'en') LANG = 'en';
document.documentElement.lang = LANG;
const I18N_MISSING = new Set();  // Тексты без перевода (для отладки: I18N_MISSING в консоли).


// Ключ словаря: переносы строк с отступами (из разметки в коде) значения не имеют:
function i18nKey(s) {
    return String(s).replace(/\n[ \t]+/g, ' ');
}


// Перевести строку (i18n('Текст')):
function i18n(s) {
    if (LANG === 'ru' || s == null) return s;
    const k = i18nKey(s), v = I18N_EN[k];
    if (v === undefined) { I18N_MISSING.add(k); return s; }
    return v;
}


// Перевести шаблонную строку с подстановками: TR`Поток ${i}` -> "Thread 3":
function TR(strings, ...vals) {
    let key = strings[0];
    for (let i = 0; i < vals.length; i++) key += '{' + i + '}' + strings[i + 1];
    let pattern = key;
    if (LANG !== 'ru') {
        const v = I18N_EN[i18nKey(key)];
        if (v === undefined) I18N_MISSING.add(i18nKey(key));
        else pattern = v;
    }
    return pattern.replace(/\{(\d+)\}/g, (m, i) => vals[+i]);
}


// Перевести готовую разметку страницы (тексты и подсказки):
function translateDom(root) {
    if (LANG === 'ru') return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const n of nodes) {
        const text = n.nodeValue, core = text.replace(/\s+/g, ' ').trim();
        if (!/[А-Яа-яЁё]/.test(core)) continue;
        const tr = i18n(core);
        if (tr !== core) n.nodeValue = text.match(/^\s*/)[0] + tr + text.match(/\s*$/)[0];
    }
    for (const el of root.querySelectorAll('[title], [placeholder]')) {
        for (const a of ['title', 'placeholder']) {
            const v = el.getAttribute(a);
            if (v && /[А-Яа-яЁё]/.test(v)) el.setAttribute(a, i18n(v.replace(/\s+/g, ' ').trim()));
        }
    }
}


// Сменить язык (страница перезагружается, чтобы всё перестроилось):
function setLang(lang) {
    try { localStorage.setItem('sysdeck.lang', JSON.stringify(lang)); } catch { /* Приватный режим. */ }
    location.reload();
}
